import * as THREE from 'three';
import { VehicleBase } from './VehicleBase';
import { PhysicsWorld } from '../../physics/PhysicsWorld';
import { InputManager } from '../../core/InputManager';
import { EventBus } from '../../core/EventBus';

export class Airplane extends VehicleBase {
  private propeller?: THREE.Mesh;
  private airspeed: number = 0;
  private pitch: number = 0;
  private roll: number = 0;
  private yaw: number = 0;

  constructor(physicsWorld: PhysicsWorld, initialPosition: THREE.Vector3) {
    super(physicsWorld, initialPosition, 'plane', 'Mallard Stunt Plane');
    this.maxSpeed = 320;
    this.acceleration = 24;
    this.driverSeatOffset.set(0, 0.6, 0);
    this.exitOffset.set(-2.5, 0, 0);

    this.buildModel();
    this.setupPhysics();
  }

  public buildModel(): void {
    const fuselageMat = new THREE.MeshStandardMaterial({ color: 0xee5500, metalness: 0.5, roughness: 0.3 }); // Aerobatic Orange
    const wingMat = new THREE.MeshStandardMaterial({ color: 0xffffff, roughness: 0.4 });
    const metalMat = new THREE.MeshStandardMaterial({ color: 0x222222, metalness: 0.8, roughness: 0.2 });

    // Fuselage
    const body = new THREE.Mesh(new THREE.BoxGeometry(1.4, 1.4, 7.5), fuselageMat);
    body.position.y = 1.2;
    body.castShadow = true;
    this.group.add(body);

    // Main Wings
    const wings = new THREE.Mesh(new THREE.BoxGeometry(11.0, 0.12, 1.8), wingMat);
    wings.position.set(0, 1.3, 0.6);
    wings.castShadow = true;
    this.group.add(wings);

    // Tail Fin & Horizontal Stabilizer
    const vTail = new THREE.Mesh(new THREE.BoxGeometry(0.12, 1.8, 1.4), fuselageMat);
    vTail.position.set(0, 2.0, -3.2);
    this.group.add(vTail);

    const hTail = new THREE.Mesh(new THREE.BoxGeometry(3.6, 0.1, 1.0), wingMat);
    hTail.position.set(0, 1.4, -3.2);
    this.group.add(hTail);

    // Propeller
    const propGeo = new THREE.BoxGeometry(0.12, 2.2, 0.2);
    this.propeller = new THREE.Mesh(propGeo, metalMat);
    this.propeller.position.set(0, 1.2, 3.8);
    this.group.add(this.propeller);

    // Wheels
    [-1.2, 1.2].forEach((x) => {
      const w = new THREE.Mesh(new THREE.CylinderGeometry(0.3, 0.3, 0.2), metalMat);
      w.rotateZ(Math.PI / 2);
      w.position.set(x, 0.3, 0.8);
      w.castShadow = true;
      this.group.add(w);
    });

    this.group.position.copy(this.initialPosition);
  }

  private setupPhysics(): void {
    const bodyDesc = this.physicsWorld.rapier.RigidBodyDesc.dynamic()
      .setTranslation(this.initialPosition.x, this.initialPosition.y + 0.8, this.initialPosition.z)
      .setLinearDamping(0.4)
      .setAngularDamping(2.0)
      .setCanSleep(false);

    this.rigidBody = this.physicsWorld.world.createRigidBody(bodyDesc);
    const colliderDesc = this.physicsWorld.rapier.ColliderDesc.cuboid(1.5, 0.8, 3.6);
    this.collider = this.physicsWorld.world.createCollider(colliderDesc, this.rigidBody);
  }

  public update(delta: number, input: InputManager): void {
    if (!this.rigidBody) return;

    if (this.isOccupied) {
      const inputState = input.state;
      const throttle = inputState.forward ? 1 : inputState.backward ? -0.5 : 0;
      const pitchInput = (inputState.jump || inputState.sprint ? 1 : 0) - (inputState.crouch ? 1 : 0);
      const rollInput = (inputState.left ? 1 : 0) - (inputState.right ? 1 : 0);

      // Accelerate airspeed
      if (throttle > 0) {
        this.airspeed = Math.min(this.airspeed + this.acceleration * delta, this.maxSpeed / 3.6);
      } else if (throttle < 0) {
        this.airspeed = Math.max(this.airspeed - this.acceleration * delta, 0);
      }

      // Lift generated by airspeed
      const lift = Math.min(Math.pow(this.airspeed / 20, 2) * 9.8, 25.0);

      // Pitch, roll, yaw authority increases with airspeed
      const controlFactor = Math.min(this.airspeed / 25, 1.0);
      this.pitch += pitchInput * delta * 1.5 * controlFactor;
      this.roll = THREE.MathUtils.lerp(this.roll, rollInput * 0.7 * controlFactor, delta * 5);
      this.yaw += -this.roll * delta * 1.2 * controlFactor;

      const forward = new THREE.Vector3(Math.sin(this.yaw), Math.sin(this.pitch), Math.cos(this.yaw)).normalize();

      this.rigidBody.setLinvel(
        {
          x: forward.x * this.airspeed,
          y: forward.y * this.airspeed + (this.airspeed > 25 ? lift - 9.8 : -9.8),
          z: forward.z * this.airspeed,
        },
        true
      );

      const euler = new THREE.Euler(this.pitch, this.yaw, this.roll, 'YXZ');
      this.rigidBody.setRotation(new THREE.Quaternion().setFromEuler(euler), true);

      this.speed = Math.round(this.airspeed * 3.6);
      EventBus.getInstance().emit('SPEED_CHANGE', { speed: this.speed, maxSpeed: this.maxSpeed });
    }

    if (this.propeller) {
      this.propeller.rotation.z += (this.isOccupied ? 35 : 5) * delta;
    }

    const t = this.rigidBody.translation();
    const r = this.rigidBody.rotation();
    this.group.position.set(t.x, t.y, t.z);
    this.group.quaternion.set(r.x, r.y, r.z, r.w);
  }
}
